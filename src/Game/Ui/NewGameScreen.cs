using ColonySim.Core;
using Godot;

namespace ColonySim.Game;

/// <summary>
/// Start screen: seed (random by default) and map size, Generate with a progress bar, and the list of saves with
/// Load. Generation and loading run on a worker thread; on success the map goes to <see cref="GameSession"/> and the
/// map scene opens. Errors are shown in red and the screen stays usable.
/// </summary>
public partial class NewGameScreen : Control
{
    public const string ScenePath = "res://scenes/new_game.tscn";
    static readonly Color BackgroundColor = Color.FromHtml("#11141b");

    /// <summary>The screenshot harness skips this screen once, on start; later visits (its menu checks) stay here.</summary>
    static bool _harnessForwarded;

    LineEdit _seed = null!;
    OptionButton _size = null!;
    Button _generate = null!, _load = null!;
    ProgressBar _progress = null!;
    Label _stage = null!, _error = null!;
    ItemList _saves = null!;
    bool _busy;

    // Exposed for the screenshot harness, which drives the screen like a player.
    public LineEdit SeedField => _seed;
    public OptionButton SizeField => _size;
    public Button GenerateButton => _generate;
    public ItemList SaveList => _saves;
    public Button LoadButton => _load;
    public string ErrorText => _error.Visible ? _error.Text : "";

    public override void _Ready()
    {
        if (!string.IsNullOrEmpty(OS.GetEnvironment(MapScene.ShotsEnv)) && !_harnessForwarded)
        {
            // The harness map is generated by MapScene itself (fixed seed, COLONYSIM_SHOTS_SIZE).
            _harnessForwarded = true;
            GameSession.Map = null;
            Callable.From(() => GetTree().ChangeSceneToFile(MapScene.ScenePath)).CallDeferred();
            return;
        }

        SetAnchorsAndOffsetsPreset(LayoutPreset.FullRect);
        AddChild(new ColorRect { Color = BackgroundColor, AnchorRight = 1, AnchorBottom = 1, MouseFilter = MouseFilterEnum.Ignore });
        var center = new CenterContainer { AnchorRight = 1, AnchorBottom = 1 };
        AddChild(center);
        var panel = Hud.Panel("Panel", 10);
        center.AddChild(panel);
        var box = new VBoxContainer { CustomMinimumSize = new Vector2(460, 0) };
        box.AddThemeConstantOverride("separation", 10);
        panel.AddChild(box);

        box.AddChild(Caption("ColonySim", 28, Hud.TextColor));
        box.AddChild(Caption("New game", 17, Hud.TextColor));

        var grid = new GridContainer { Columns = 2 };
        grid.AddThemeConstantOverride("h_separation", 12);
        grid.AddThemeConstantOverride("v_separation", 8);
        grid.AddChild(Caption("Seed", 14, Hud.DimTextColor));
        var seedRow = new HBoxContainer { SizeFlagsHorizontal = SizeFlags.ExpandFill };
        _seed = new LineEdit { Text = RandomSeed().ToString(), SizeFlagsHorizontal = SizeFlags.ExpandFill };
        _seed.TextSubmitted += _ => Generate();
        seedRow.AddChild(_seed);
        seedRow.AddChild(MenuButton("Random", () => _seed.Text = RandomSeed().ToString()));
        grid.AddChild(seedRow);
        grid.AddChild(Caption("Map size", 14, Hud.DimTextColor));
        _size = new OptionButton { SizeFlagsHorizontal = SizeFlags.ExpandFill };
        foreach (var size in Enum.GetValues<MapSize>())
        {
            int d = MapSizes.Dimension(size);
            _size.AddItem($"{size} ({d} × {d})", (int)size);
        }
        _size.Select((int)MapSize.Large);
        grid.AddChild(_size);
        box.AddChild(grid);

        _generate = MenuButton("Generate", Generate);
        box.AddChild(_generate);
        _progress = new ProgressBar { MinValue = 0, MaxValue = 1, Step = 0.001, Visible = false };
        box.AddChild(_progress);
        _stage = Hud.Text("Stage", 13, Hud.DimTextColor);
        _stage.Visible = false;
        box.AddChild(_stage);

        box.AddChild(new HSeparator());
        box.AddChild(Caption("Saved games", 17, Hud.TextColor));
        _saves = new ItemList { CustomMinimumSize = new Vector2(0, 180) };
        _saves.ItemSelected += _ => UpdateButtons();
        _saves.ItemActivated += _ => Load();
        box.AddChild(_saves);
        _load = MenuButton("Load", Load);
        box.AddChild(_load);

        _error = Hud.Text("Error", 13, Hud.ErrorColor);
        _error.AutowrapMode = TextServer.AutowrapMode.WordSmart;
        _error.Visible = false;
        box.AddChild(_error);

        RefreshSaves();
        _generate.GrabFocus();
    }

    static int RandomSeed() => Random.Shared.Next(1, int.MaxValue);

    void RefreshSaves()
    {
        _saves.Clear();
        try
        {
            foreach (string file in SaveGames.List()) _saves.AddItem(file);
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            ShowError($"Couldn't list the saves: {e.Message}");
        }
        UpdateButtons();
    }

    void UpdateButtons()
    {
        _generate.Disabled = _busy;
        _seed.Editable = !_busy;
        _size.Disabled = _busy;
        _saves.MouseFilter = _busy ? MouseFilterEnum.Ignore : MouseFilterEnum.Stop;
        _load.Disabled = _busy || _saves.GetSelectedItems().Length == 0;
    }

    async void Generate()
    {
        if (_busy) return;
        if (!int.TryParse(_seed.Text.Trim(), out int seed))
        {
            ShowError("The seed must be a whole number.");
            return;
        }
        var settings = MapSettings.Create(seed, (MapSize)_size.GetSelectedId());
        await Run($"Generating {_size.Text}", () => MapGenerator.Generate(settings, new DeferredProgress(this)));
    }

    async void Load()
    {
        if (_busy) return;
        int[] selected = _saves.GetSelectedItems();
        if (selected.Length == 0) return;
        string file = _saves.GetItemText(selected[0]);
        await Run($"Loading {file}", () => SaveGames.Load(file), file);
    }

    /// <summary>Runs <paramref name="work"/> on a worker thread; opens the map on success, shows the error otherwise.</summary>
    async Task Run(string what, Func<ColonyMap> work, string? loadingFile = null)
    {
        _busy = true;
        UpdateButtons();
        _error.Visible = false;
        _progress.Visible = _stage.Visible = true;
        _progress.Value = 0;
        _progress.Indeterminate = loadingFile != null; // loading reports no progress
        _stage.Text = what + "…";
        try
        {
            var map = await Task.Run(work);
            GameSession.Map = map;
            GetTree().ChangeSceneToFile(MapScene.ScenePath);
        }
        catch (Exception e)
        {
            _busy = false;
            _progress.Visible = _stage.Visible = false;
            ShowError(loadingFile != null ? $"Couldn't load {loadingFile}: {e.Message}" : $"Generation failed: {e.Message}");
            UpdateButtons();
        }
    }

    void ShowProgress(GenerationProgress p)
    {
        if (!_busy) return;
        _progress.Value = p.Fraction;
        _stage.Text = $"{p.Stage}…";
    }

    void ShowError(string message)
    {
        _error.Text = message;
        _error.Visible = true;
    }

    static Label Caption(string text, int size, Color color)
    {
        var label = Hud.Text(text, size, color);
        label.Text = text;
        return label;
    }

    static Button MenuButton(string text, Action onPressed)
    {
        var button = new Button { Text = text };
        button.AddThemeFontSizeOverride("font_size", 14);
        Hud.StyleButton(button, Hud.ActiveColor, Hud.ActiveTextColor);
        button.Pressed += onPressed;
        return button;
    }

    /// <summary>Forwards generation progress from the worker thread to the screen on the main thread.</summary>
    sealed class DeferredProgress(NewGameScreen screen) : IProgress<GenerationProgress>
    {
        public void Report(GenerationProgress value) =>
            Callable.From(() => { if (IsInstanceValid(screen)) screen.ShowProgress(value); }).CallDeferred();
    }
}
